import { readFileSync, writeFileSync } from 'node:fs'

const URL_PSL = 'https://publicsuffix.org/list/public_suffix_list.dat'
const OUT = 'src/guard/psl-data.ts'

// ICANN section only, punycoded, comments and blank lines dropped, sorted.
export function icannRules(datText: string): string[] {
    const begin = datText.indexOf('// ===BEGIN ICANN DOMAINS===')
    const end = datText.indexOf('// ===END ICANN DOMAINS===')
    if (begin < 0 || end < begin) throw new Error('ICANN section markers not found')
    const rules = new Set<string>()
    for (const raw of datText.slice(begin, end).split(/\r?\n/)) {
        const line = raw.trim()
        if (line === '' || line.startsWith('//')) continue
        const prefix = line.startsWith('!') ? '!' : line.startsWith('*.') ? '*.' : ''
        rules.add(prefix + new URL('http://' + line.slice(prefix.length)).hostname)
    }
    return [...rules].sort()
}

// A template literal keeps the file prettier-clean; rules never contain backticks, backslashes or `${`.
export function renderData(rules: string[], source: string, date: string): string {
    return `// Generated by scripts/update-psl.ts from ${source} on ${date}. Do not edit.\nexport const PSL_ICANN = \`${rules.join('\n')}\`\n`
}

if (import.meta.main) {
    const i = process.argv.indexOf('--file')
    const path = i >= 0 ? process.argv[i + 1] : undefined
    if (i >= 0 && !path) throw new Error('--file needs a path')
    const text = path ? readFileSync(path, 'utf8') : await (await fetch(URL_PSL)).text()
    const rules = icannRules(text)
    writeFileSync(OUT, renderData(rules, URL_PSL, new Date().toISOString().slice(0, 10)))
    console.log(`wrote ${rules.length} rules to ${OUT}`)
}
